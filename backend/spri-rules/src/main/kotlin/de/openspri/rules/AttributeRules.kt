package de.openspri.rules

/** Cardinality of an attribute in Anlage 1. `null` in a rule means: the attribute is not allowed. */
data class Cardinality(val min: Int, val max: Int?) {
    fun accepts(count: Int) = count >= min && (max == null || count <= max)

    override fun toString() = if (min == max) "$min" else "$min..${max ?: "*"}"

    companion object {
        private val RANGE = Regex("""(\d+)\.\.(\d+|\*)""")

        fun parse(value: String): Cardinality? = when {
            value.isBlank() -> null
            value.matches(Regex("""\d+""")) -> value.toInt().let { Cardinality(it, it) }
            else -> RANGE.matchEntire(value)?.let { Cardinality(it.groupValues[1].toInt(), it.groupValues[2].toIntOrNull()) }
                ?: throw IllegalArgumentException("unknown cardinality '$value'")
        }
    }
}

enum class RuleKind { ORDER, MESSAGE }

/**
 * One attribute of Anlage 1 with its XML location and the cardinality per column.
 *
 * @property row row in Anlage 1 (sheet Auftragsstruktur or Meldungsstruktur), for traceability
 * @property path element names from the payload root; a segment with several names is an XSD choice
 * @property cardinalities column (e.g. `NEU/FTTH`, `KUE-AG/FTTC`, `ABM`) to cardinality; a column that is
 *   present with value `null` means "not allowed"; a missing column means "no statement"
 */
data class AttributeRule(
    val kind: RuleKind,
    val row: Int,
    val labelPath: String,
    val path: List<Set<String>>,
    val cardinalities: Map<String, Cardinality?>,
    val condition: Condition? = null,
)

/**
 * Condition from the column "Anmerkung" of Anlage 1 (src/generator/resources/anlage1-conditions.txt).
 * If it is not fulfilled, the attribute is not allowed.
 */
data class Condition(val field: Field, val values: Set<String>, val negated: Boolean) {
    enum class Field { GF, AKZ }

    fun fulfilled(context: Map<Field, String?>): Boolean {
        val value = context[field] ?: return true // unknown context: do not restrict
        return (value in values) != negated
    }

    companion object {
        fun parse(text: String): Condition? {
            if (text.isBlank()) return null
            val (mode, field, list) = text.trim().split(' ', limit = 3)
            return Condition(Field.valueOf(field), list.split(',').map { it.trim() }.toSet(), negated = mode == "not")
        }
    }
}

/** The rule table generated from Anlage 1 at build time (module spri-rules, resource spri/v4/anlage1-rules.tsv). */
class AttributeRules(val rules: List<AttributeRule>) {

    fun of(kind: RuleKind) = rules.filter { it.kind == kind }

    companion object {
        private const val RESOURCE = "spri/v4/anlage1-rules.tsv"

        fun load(): AttributeRules {
            val text = requireNotNull(AttributeRules::class.java.classLoader.getResourceAsStream(RESOURCE)) {
                "$RESOURCE not found - generated by the Gradle task :spri-rules:generateAnlage1Rules"
            }.bufferedReader(Charsets.UTF_8).readText()
            return AttributeRules(parse(text))
        }

        fun parse(text: String): List<AttributeRule> = text.lineSequence()
            .filter { it.isNotBlank() && !it.startsWith("#") }
            .map { line ->
                val parts = line.split('\t').let { it + List(maxOf(0, 6 - it.size)) { "" } }
                val (kind, row, label, path, columns) = parts
                AttributeRule(
                    kind = RuleKind.valueOf(kind),
                    row = row.toInt(),
                    labelPath = label,
                    path = path.split('/').map { it.split('|').toSet() },
                    cardinalities = columns.split(';').filter { it.isNotEmpty() }.associate { entry ->
                        val (column, value) = entry.split('=', limit = 2)
                        column to Cardinality.parse(value)
                    },
                    condition = Condition.parse(parts[5]),
                )
            }.toList()
    }
}
